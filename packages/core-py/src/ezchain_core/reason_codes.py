"""The stable reason-code vocabulary for every failure that can block or move money.

One code, one meaning, one home. Every layer imports its codes from here instead of
re-typing a literal, and :mod:`docs/REASON-CODES.md` is hand-maintained and test-checked
against every emission site, so the document cannot drift from the code. The drift guard
in ``tests/test_reason_codes.py`` fails when a code is emitted anywhere without a row here.

Stability promise: a code's **string** and its **meaning** are permanent. Within a
minor release a code may gain a new emission site or a friendlier ``message``; it is
never renamed, never re-used for a different failure and never removed. A failure that
no longer exists keeps its row, retired, because logs and persisted rows outlive it.

``message`` is display text. ``summary`` is the operator detail: what happened and what
to do. ``http_status`` is set only where the code actually crosses the HTTP edge today;
``None`` means the code never leaves the process as an HTTP error.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Final, Literal

Category = Literal[
    "auth",
    "validation",
    "risk",
    "market",
    "custody",
    "approval",
    "signing",
    "governance",
    "strategy",
    "graph",
    "plugin",
    "backtest",
    "protection",
    "engine",
    "adapter",
    "observability",
    "outcome",
]
Severity = Literal["info", "warning", "critical"]
Layer = Literal["core", "sdk", "adapters", "api", "engine", "executor"]


@dataclass(frozen=True)
class ReasonSpec:
    """One reason code and everything a caller needs to handle it."""

    code: str
    category: Category
    layer: Layer
    source: str
    summary: str
    message: str
    http_status: int | None = None
    retryable: bool = False
    severity: Severity = "warning"

    @property
    def is_denial(self) -> bool:
        """True when this code refuses an action; informational outcomes return False."""
        return self.category != "outcome"


