def reason(code: str) -> ReasonSpec:
    """Look one code up, failing loudly so an unknown code never reaches a caller."""
    try:
        return REASON_CODES[code]
    except KeyError:  # pragma: no cover - only an unmigrated literal can reach this
        raise KeyError(f"{code} is not in the reason-code taxonomy") from None


def message_for(code: str) -> str:
    """Display text for a code; an unknown code renders as itself, never as blank."""
    spec = REASON_CODES.get(code)
    return spec.message if spec is not None else code


def codes_in(category: Category) -> tuple[str, ...]:
    """Every code in one category, in declaration order."""
    return tuple(spec.code for spec in _SPECS if spec.category == category)


