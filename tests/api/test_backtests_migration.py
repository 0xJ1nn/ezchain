"""The backtests migration: SQLite tail and a fresh Postgres database (CONTRACT I8)."""

from __future__ import annotations

import os
from collections.abc import Iterator
from pathlib import Path
from uuid import uuid4

import psycopg
import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import Engine, make_url
from sqlalchemy.orm import Session

from ezchain_api.db import alembic_config, database_revision, head_revision

BACKTEST_COLUMNS = {"id", "strategy_id", "request", "result", "created_at"}


def _config(url: str) -> Config:
    config = alembic_config()
    config.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    config.attributes["database_url"] = url
    return config


def _assert_backtests_table(engine: Engine) -> None:
    inspector = inspect(engine)
    assert "backtests" in inspector.get_table_names()
    columns = {column["name"]: column for column in inspector.get_columns("backtests")}
    assert set(columns) == BACKTEST_COLUMNS
    assert columns["strategy_id"]["nullable"] is True
    assert columns["request"]["nullable"] is False
    assert columns["result"]["nullable"] is False
    assert "created_at" in {column["name"] for column in inspector.get_columns("backtests")}


def test_backtests_upgrades_a_sqlite_database(tmp_path: Path) -> None:
    database = tmp_path / "backtests.db"
    url = f"sqlite+pysqlite:///{database}"
    config = _config(url)
    engine = create_engine(url)
    # 0003 uses Postgres-only DDL; start at 0005 and run the tail. The strategies table is
    # seeded because later revisions add columns to it; ``paper_orders`` is seeded because
    # the trade-policy revision adds a column to it. This test proves the tail only.
    with engine.begin() as connection:
        connection.execute(text("CREATE TABLE strategies (id VARCHAR(36) PRIMARY KEY)"))
        connection.execute(
            text("CREATE TABLE paper_orders (id VARCHAR(36) PRIMARY KEY, amount_usd TEXT)")
        )
    command.stamp(config, "0005_price_precision")
    command.upgrade(config, "head")
    try:
        _assert_backtests_table(engine)
        with Session(engine) as session:
            assert database_revision(session) == head_revision()
    finally:
        engine.dispose()


def _postgres_url() -> str:
    url = os.environ.get("EZCHAIN_TEST_DATABASE_URL", "")
    if not url.startswith("postgresql"):
        pytest.skip("EZCHAIN_TEST_DATABASE_URL is not a Postgres test database")
    return url


@pytest.fixture
def scratch_postgres() -> Iterator[str]:
    """A disposable database on the test server, dropped afterwards."""
    base = _postgres_url()
    parsed = make_url(base)
    name = f"ezchain_backtests_{uuid4().hex[:8]}_test"
    admin = parsed.set(drivername="postgresql", database="postgres")
    with psycopg.connect(admin.render_as_string(hide_password=False), autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{name}"')
    created = parsed.set(database=name)
    try:
        yield created.render_as_string(hide_password=False)
    finally:
        with psycopg.connect(admin.render_as_string(hide_password=False), autocommit=True) as conn:
            conn.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')


def test_fresh_postgres_database_reaches_head_with_backtests(scratch_postgres: str) -> None:
    config = _config(scratch_postgres)
    command.upgrade(config, "head")

    engine = create_engine(scratch_postgres)
    try:
        _assert_backtests_table(engine)
        with Session(engine) as session:
            assert database_revision(session) == head_revision()
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"model and migrations disagree: {exc}")
    finally:
        engine.dispose()
