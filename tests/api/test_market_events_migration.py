"""The market persistence revision: fresh apply, forward-only, idempotent identity.

Two databases matter and both are tested. SQLite is what every API test and the desktop
build run, so the revision must apply there. Postgres is the deployment target, and a fresh
Postgres database upgraded from scratch must then pass ``alembic check`` — the same thing
``tools/check-migrations.sh`` runs — so the model and the revision cannot drift.

The Postgres cases skip, never fake, when ``EZCHAIN_TEST_DATABASE_URL`` is unset. That is
also how the gate treats a missing database.
"""

from __future__ import annotations

import ast
import os
from collections.abc import Iterator
from pathlib import Path
from uuid import uuid4

import psycopg
import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy.engine import Engine, make_url
from sqlalchemy.orm import Session

from ezchain_api.db import alembic_config, database_revision, head_revision
from ezchain_api.models import MarketEventRow
from ezchain_ingest import RetentionPolicy
from ezchain_ingest.retention import DEFAULT_CANDLE_1M_DAYS, DEFAULT_RAW_DAYS

VERSIONS = Path(__file__).resolve().parents[2] / "apps/api/alembic/versions"
REVISION = "0020_market_events"
FORBIDDEN = ("drop_table", "drop_column", "truncate", "delete from", "wipe", "clean_slate")
EVENT_COLUMNS = {
    "source_name",
    "pair",
    "source_observed_at",
    "chain",
    "venue",
    "price",
    "size",
    "direction",
    "units",
    "confidence",
    "source_url",
    "observed_at",
    "schema_version",
}
IDENTITY = ["source_name", "pair", "source_observed_at"]


def _config(url: str) -> Config:
    config = alembic_config()
    config.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    config.attributes["database_url"] = url
    return config


def _upgrade_source(path: Path) -> str:
    source = path.read_text()
    tree = ast.parse(source)
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == "upgrade":
            return (ast.get_source_segment(source, node) or "").lower()
    raise AssertionError("revision has no upgrade() function")


def _assert_market_tables(engine: Engine) -> None:
    inspector = sa.inspect(engine)
    assert "market_events" in inspector.get_table_names()
    assert "market_outbox" in inspector.get_table_names()

    columns = {column["name"]: column for column in inspector.get_columns("market_events")}
    assert set(columns) == EVENT_COLUMNS
    for nullable in ("price", "size", "direction", "confidence", "source_url"):
        assert columns[nullable]["nullable"] is True, nullable
    for required in ("chain", "venue", "units", "source_observed_at", "observed_at"):
        assert columns[required]["nullable"] is False, required

    primary_key = inspector.get_pk_constraint("market_events")
    assert primary_key["constrained_columns"] == IDENTITY


def _insert_event(engine: Engine, *, source: str = "pumpfun-firehose") -> None:
    with engine.begin() as connection:
        connection.execute(
            sa.text(
                "INSERT INTO market_events "
                "(source_name, pair, source_observed_at, chain, venue, price, size, "
                " direction, units, confidence, source_url, observed_at, schema_version) "
                "VALUES (:source, 'Mint1', '2026-02-01 12:00:00+00', 'solana', 'pumpfun', "
                " 2.5, NULL, NULL, 'SOL', NULL, NULL, '2026-02-01 12:00:01+00', 1)"
            ),
            {"source": source},
        )


def test_the_head_is_the_market_persistence_revision() -> None:
    assert head_revision() == REVISION


def test_the_revision_is_forward_only() -> None:
    body = _upgrade_source(VERSIONS / f"{REVISION}.py")
    found = [token for token in FORBIDDEN if token in body]
    assert not found, f"destructive upgrade operation(s): {found}"


def test_the_revision_only_adds_tables_and_indexes() -> None:
    """A forward-only data migration would be a backfill here. There is none."""
    body = _upgrade_source(VERSIONS / f"{REVISION}.py")
    statements = ("op.create_table", "op.create_index", "sa.text")
    allowed = [line.strip() for line in body.splitlines() if line.strip().startswith(statements)]
    assert allowed, "the revision creates nothing?"


def test_timed_retention_days_are_not_a_second_home() -> None:
    """The revision reads no window of its own; the policy in ingest is the one home."""
    body = _upgrade_source(VERSIONS / f"{REVISION}.py")
    assert "retention" not in body
    assert RetentionPolicy().raw_days == DEFAULT_RAW_DAYS
    assert RetentionPolicy().candle_1m_days == DEFAULT_CANDLE_1M_DAYS


def test_market_tables_upgrade_a_sqlite_database(tmp_path: Path) -> None:
    url = f"sqlite+pysqlite:///{tmp_path / 'market.db'}"
    config = _config(url)
    engine = sa.create_engine(url)
    try:
        # 0003 uses Postgres-only DDL, so start SQLite at 0003 and run the tail.
        with engine.begin() as connection:
            connection.execute(sa.text("CREATE TABLE strategies (id VARCHAR(36) PRIMARY KEY)"))
            connection.execute(
                sa.text(
                    "CREATE TABLE paper_orders "
                    "(id VARCHAR(36) PRIMARY KEY, idempotency_key VARCHAR(120))"
                )
            )
        command.stamp(config, "0003_paper_fill_order")
        command.upgrade(config, "head")
        _assert_market_tables(engine)
        with Session(engine) as session:
            assert database_revision(session) == head_revision()
    finally:
        engine.dispose()


def test_a_fresh_postgres_database_has_no_pending_migration(scratch_postgres: str) -> None:
    config = _config(scratch_postgres)
    command.upgrade(config, "head")

    engine = sa.create_engine(scratch_postgres)
    try:
        _assert_market_tables(engine)
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"model and migrations disagree: {exc}")
    finally:
        engine.dispose()


def test_postgres_enforces_the_identity_as_the_primary_key(scratch_postgres: str) -> None:
    config = _config(scratch_postgres)
    command.upgrade(config, "head")
    engine = sa.create_engine(scratch_postgres)
    try:
        _insert_event(engine)
        with pytest.raises(sa.exc.IntegrityError):
            _insert_event(engine)
        # A different source observing the same pair at the same instant is another row.
        _insert_event(engine, source="jupiter-quote")
        with engine.connect() as connection:
            count = connection.execute(sa.text("SELECT COUNT(*) FROM market_events")).scalar_one()
        assert count == 2
    finally:
        engine.dispose()


def test_the_primary_key_matches_the_contract_identity_in_the_model() -> None:
    assert list(MarketEventRow.__table__.primary_key.columns.keys()) == IDENTITY


def _postgres_url() -> str:
    url = os.environ.get("EZCHAIN_TEST_DATABASE_URL", "")
    if not url.startswith("postgresql"):
        pytest.skip("EZCHAIN_TEST_DATABASE_URL is not a Postgres test database")
    return url


@pytest.fixture
def scratch_postgres() -> Iterator[str]:
    """A disposable database on the test server, dropped afterwards."""
    base = _postgres_url()
    parsed = make_url(base)
    name = f"ezchain_market_mig_{uuid4().hex[:8]}_test"
    admin = parsed.set(drivername="postgresql", database="postgres").render_as_string(
        hide_password=False
    )
    with psycopg.connect(admin, autocommit=True) as connection:
        connection.execute(f'CREATE DATABASE "{name}"')
    created = parsed.set(database=name)
    try:
        yield created.render_as_string(hide_password=False)
    finally:
        with psycopg.connect(admin, autocommit=True) as connection:
            connection.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')
