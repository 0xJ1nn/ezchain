"""The market_candles migration on SQLite and Postgres (CONTRACT I8).

SQLite proves the revision runs at all on the database the API tests use. Postgres proves
the fresh-database path: every revision from scratch, then ``alembic check`` so the model
and the migration cannot drift apart.
"""

from __future__ import annotations

import os
from collections.abc import Iterator
from pathlib import Path
from uuid import uuid4

import psycopg
import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import Engine, make_url
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from ezchain_api.db import alembic_config, database_revision, head_revision

CANDLE_COLUMNS = {
    "id",
    "chain",
    "token_address",
    "pool_address",
    "timeframe",
    "open_time",
    "open",
    "high",
    "low",
    "close",
    "volume",
    "source",
    "fetched_at",
}
UNIQUE_KEY = ["chain", "token_address", "timeframe", "open_time"]


def _config(url: str) -> Config:
    config = alembic_config()
    config.set_main_option("sqlalchemy.url", url.replace("%", "%%"))
    config.attributes["database_url"] = url
    return config


def _insert_bar(engine: Engine, open_time: str) -> None:
    with engine.begin() as connection:
        connection.execute(
            text(
                "INSERT INTO market_candles "
                "(id, chain, token_address, pool_address, timeframe, open_time, "
                " open, high, low, close, volume, source, fetched_at) "
                "VALUES (:id, 'ethereum', '0xtoken', '0xpool', '5m', :open_time, "
                " 1, 2, 1, 2, NULL, 'geckoterminal', :open_time)"
            ),
            {"id": uuid4().hex, "open_time": open_time},
        )


def _assert_candle_table(engine: Engine) -> None:
    inspector = inspect(engine)
    assert "market_candles" in inspector.get_table_names()
    columns = {column["name"]: column for column in inspector.get_columns("market_candles")}
    assert set(columns) == CANDLE_COLUMNS
    assert columns["volume"]["nullable"] is True
    assert columns["open"]["nullable"] is False
    unique = [
        constraint["column_names"]
        for constraint in inspector.get_unique_constraints("market_candles")
    ]
    assert UNIQUE_KEY in unique


def _assert_duplicate_bar_is_rejected(engine: Engine) -> None:
    _insert_bar(engine, "2026-10-22 12:00:00")
    with pytest.raises(IntegrityError):
        _insert_bar(engine, "2026-10-22 12:00:00")


def test_market_candles_upgrades_a_sqlite_database(tmp_path: Path) -> None:
    database = tmp_path / "candles.db"
    url = f"sqlite+pysqlite:///{database}"
    config = _config(url)
    engine = create_engine(url)
    # 0003 uses Postgres-only DDL, so start a SQLite database at 0003 and run the tail.
    # The strategies table is seeded because a later revision adds columns to it;
    # ``paper_orders`` is seeded because the trade-policy revision alters it.
    with engine.begin() as connection:
        connection.execute(text("CREATE TABLE strategies (id VARCHAR(36) PRIMARY KEY)"))
        connection.execute(
            text("CREATE TABLE paper_orders (id VARCHAR(36) PRIMARY KEY, amount_usd TEXT)")
        )
    command.stamp(config, "0003_paper_fill_order")
    command.upgrade(config, "head")
    try:
        _assert_candle_table(engine)
        _assert_duplicate_bar_is_rejected(engine)
        with Session(engine) as session:
            assert database_revision(session) == head_revision()
    finally:
        engine.dispose()


def _postgres_url() -> str:
    url = os.environ.get("EZCHAIN_TEST_DATABASE_URL", "")
    if not url.startswith("postgresql"):
        pytest.skip("EZCHAIN_TEST_DATABASE_URL is not a Postgres test database")
    return url


@pytest.fixture
def scratch_postgres() -> Iterator[str]:
    """A disposable database on the test server, dropped afterwards."""
    base = _postgres_url()
    parsed = make_url(base)
    name = f"ezchain_candles_{uuid4().hex[:8]}_test"
    admin = parsed.set(drivername="postgresql", database="postgres")
    with psycopg.connect(admin.render_as_string(hide_password=False), autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{name}"')
    created = parsed.set(database=name)
    try:
        yield created.render_as_string(hide_password=False)
    finally:
        with psycopg.connect(admin.render_as_string(hide_password=False), autocommit=True) as conn:
            conn.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')


def test_fresh_postgres_database_has_no_pending_migration(scratch_postgres: str) -> None:
    config = _config(scratch_postgres)
    command.upgrade(config, "head")

    engine = create_engine(scratch_postgres)
    try:
        _assert_candle_table(engine)
        _assert_duplicate_bar_is_rejected(engine)
        # The model and the migration must agree; this is what tools/check-migrations.sh
        # runs on a fresh database.
        command.check(config)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"model and migrations disagree: {exc}")
    finally:
        engine.dispose()
