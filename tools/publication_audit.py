#!/usr/bin/env python3
"""Check issue text before it reaches the public tracker.

Public text is finished prose for a reader who is deciding whether to trust the
software with money. The mechanical part of that rule is checked here: an item
must carry no internal board identifier, no assistant or model name, and an
acceptance section. The check is local and read-only. It never creates, edits
or publishes an issue, and it never changes repository settings.

Usage:
    gh issue list --repo OWNER/REPO --state open --json number,title,body,labels \
        > issues.json
    python3 tools/publication_audit.py --issues issues.json

    python3 tools/publication_audit.py --draft draft.json   # single item file
    python3 tools/publication_audit.py --issues issues.json --json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

# Board and task identifiers are meaningful inside the workspace only.
INTERNAL_ID = re.compile(
    r"\b(?:EZ|EZW|EZX|RUST)-\d{1,4}\b"
    r"|\b(?:M[0-5]|P[0-3])\b"
)

# A reader does not need to know which assistant wrote a line, or which model
# produced it. Product words such as "agent" are deliberately not listed here.
ASSISTANT = re.compile(
    r"\b(?:Claude|GPT(?:-[0-9]+(?:-[a-z]+)?)?|Gemini|Hermes|OpenClaw|DeepSeek"
    r"|Copilot|Codex|OpenAI|Anthropic|opencode|hy4[- ][a-z]+)\b",
    re.I,
)
ATTRIBUTION = re.compile(r"\b(?:generated by|assisted by|written by an? AI)\b", re.I)

# Planning vocabulary that describes the workspace rather than the software.
BOARD_VOCABULARY = re.compile(
    r"\b(?:sprint|epic|swarm|handoff|task packet|foreman|caretaker|workqueue|board)\b",
    re.I,
)

ACCEPTANCE = re.compile(r"(?im)^\s*(?:#{1,6}\s*)?acceptance(?:\s+criteria)?\b")

BLOCKING = {"internal-id", "assistant-name", "no-acceptance"}


def check_item(number: Any, title: str, body: str, labels: list[str] | None = None) -> list[dict]:
    """Return every finding on one issue. Number is kept for the report only."""
    findings: list[dict] = []

    def add(kind: str, field: str, text: str, match: re.Match[str]) -> None:
        start = max(0, match.start() - 40)
        end = min(len(text), match.end() + 40)
        findings.append(
            {
                "issue": number,
                "kind": kind,
                "field": field,
                "severity": "block" if kind in BLOCKING else "review",
                "detail": text[start:end].replace("\n", " "),
            }
        )

    for field, text in (("title", title or ""), ("body", body or "")):
        for match in INTERNAL_ID.finditer(text):
            add("internal-id", field, text, match)
        for match in ASSISTANT.finditer(text):
            add("assistant-name", field, text, match)
        for match in ATTRIBUTION.finditer(text):
            add("assistant-name", field, text, match)
        for match in BOARD_VOCABULARY.finditer(text):
            add("board-vocabulary", field, text, match)

    if not ACCEPTANCE.search(body or ""):
        findings.append(
            {
                "issue": number,
                "kind": "no-acceptance",
                "field": "body",
                "severity": "block",
                "detail": "no acceptance section",
            }
        )
    if not labels:
        findings.append(
            {
                "issue": number,
                "kind": "no-labels",
                "field": "labels",
                "severity": "review",
                "detail": "no labels",
            }
        )
    return findings


def load_items(path: Path) -> list[tuple[Any, str, str, list[str]]]:
    data = json.loads(path.read_text())
    if isinstance(data, dict):
        data = [data]
    items = []
    for row in data:
        labels = [
            label["name"] if isinstance(label, dict) else label for label in row.get("labels", [])
        ]
        items.append(
            (row.get("number", "draft"), row.get("title", ""), row.get("body", ""), labels)
        )
    return items


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--issues", type=Path, help="JSON export of one or more issues")
    parser.add_argument("--draft", type=Path, help="local JSON draft of a single item")
    parser.add_argument("--json", action="store_true", help="print findings as JSON")
    parser.add_argument("--strict", action="store_true", help="review findings also fail")
    args = parser.parse_args(argv)

    path = args.issues or args.draft
    if not path:
        parser.error("nothing to check: pass --issues or --draft")

    items = load_items(path)
    findings = []
    for number, title, body, labels in items:
        findings.extend(check_item(number, title, body, labels))

    if args.json:
        print(json.dumps(findings, indent=2))
    else:
        for finding in findings:
            print(
                f"#{finding['issue']} {finding['field']}: {finding['kind']} "
                f"({finding['severity']}) - {finding['detail']}"
            )
        count = len({(f["issue"], f["kind"]) for f in findings})
        print(f"checked {len(items)} items, {count} findings")

    failed = any(
        f["severity"] == "block" or (args.strict and f["severity"] == "review") for f in findings
    )
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
