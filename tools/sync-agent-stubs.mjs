// Regenerate (or verify) the thin agent stubs that point at AGENTS.md.
// Usage: node tools/sync-agent-stubs.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const check = process.argv.includes("--check");

const pointer = (tool, extra = "") =>
	`# ${tool} instructions\n\nRead \`AGENTS.md\`. It is canonical for this repository and wins over this file.${extra}\n\n<!-- generated by tools/sync-agent-stubs.mjs -->\n`;

const targets = {
	"CLAUDE.md": pointer("Claude"),
	".github/copilot-instructions.md": pointer("Copilot / code-assist"),
	".codex/instructions.md": pointer("Codex"),
	".opencode/instructions.md": pointer("OpenCode"),
	".cursor/rules/ezchain.mdc": `---\ndescription: ezCHAIN canonical rules\nglobs: ["**/*"]\n---\n\nRead \`AGENTS.md\`. It is canonical for this repository and wins over this file.\n\n<!-- generated by tools/sync-agent-stubs.mjs -->\n`,
};

let failed = false;
for (const [rel, body] of Object.entries(targets)) {
	const file = join(root, rel);
	if (check) {
		const current = existsSync(file) ? readFileSync(file, "utf8") : "";
		if (current !== body) {
			console.error(`stale agent stub: ${rel}`);
			failed = true;
		}
	} else {
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, body);
		console.log(`wrote ${rel}`);
	}
}

if (check) {
	if (failed) {
		console.error("Run: node tools/sync-agent-stubs.mjs");
		process.exit(1);
	}
	console.log("agent stubs: ok");
}
