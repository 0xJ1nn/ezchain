// Generate design/tokens.css and packages/ui/src/tokens.css from design/tokens.json.
// The JSON is canonical; never hand-edit the generated CSS.
// Usage: node tools/build-tokens.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const check = process.argv.includes("--check");
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function flatten(value, path = [], out = []) {
	for (const [key, child] of Object.entries(value)) {
		if (key.startsWith("$")) continue;
		const next = [...path, kebab(key)];
		if (child && typeof child === "object" && !Array.isArray(child)) flatten(child, next, out);
		else out.push([next.join("-"), child]);
	}
	return out;
}

const entries = flatten({
	space: tokens.space,
	radius: tokens.radius,
	type: tokens.type,
	elevation: tokens.elevation,
	motion: tokens.motion,
});

// The legacy colour roles are still emitted because older pages reference them
// through the aliases below. Dark is the default theme; the light override lives
// under [data-theme="light"], matching the brand.
const lightColorEntries = flatten(tokens.color).map(([name, value]) => [
	`color-${name}`,
	value,
]);
const darkColor = tokens.dark?.color;
if (!darkColor || typeof darkColor !== "object") {
	console.error("dark theme is missing its colour roles");
	process.exit(1);
}
const darkValues = new Map(
	flatten(darkColor).map(([name, value]) => [`color-${name}`, value]),
);
for (const [name] of lightColorEntries) {
	if (!darkValues.has(name)) {
		console.error(`dark theme missing role ${name}`);
		process.exit(1);
	}
}

// Brand variables are copied verbatim from design/tokens.json. Keys are the
// brand's own custom-property names, so components use them 1:1.
const brand = tokens.brand || {};
const brandLines = Object.entries(brand.base || {}).map(([name, value]) => `  --${name}: ${value};`);
const brandLightLines = Object.entries(brand.light || {}).map(
	([name, value]) => `  --${name}: ${value};`,
);

// Old names stay as aliases while pages still use them. Where a brand variable
// already owns a name (--line-2, --mono) no alias is emitted.
const aliases = [
	["--bg", "--bg-0"],
	["--surface", "--bg-1"],
	["--surface-2", "--bg-2"],
	["--surface-3", "--bg-3"],
	["--ink", "--text-1"],
	["--ink-2", "--text-2"],
	["--muted", "--text-3"],
	["--line", "--line-1"],
	["--dash", "--line-2"],
	["--ok", "--green"],
	["--ok-bg", "--green-a"],
	["--err", "--red"],
	["--err-bg", "--red-a"],
	["--warn", "--amber"],
	["--warn-bg", "--amber-a"],
	["--info", "--blue"],
	["--info-bg", "--blue-a"],
	["--accent", "--text-1"],
	["--r", "--r-2"],
	["--r-sm", "--r-1"],
	["--sans", "--font"],
	["--shadow", "--layer-1"],
];

const line = ([name, value]) => `  --${name}: ${value};`;
const css = `/* generated by tools/build-tokens.mjs from design/tokens.json — do not edit */
:root {
  color-scheme: dark;
${brandLines.join("\n")}
${entries.map(line).join("\n")}
${[...darkValues].map(line).join("\n")}
${aliases.map(([a, b]) => `  ${a}: var(${b});`).join("\n")}
}

[data-theme="light"] {
  color-scheme: light;
${brandLightLines.join("\n")}
${lightColorEntries.map(line).join("\n")}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --motion-fast: 0ms;
    --motion-base: 0ms;
    --motion-slow: 0ms;
    --t-1: 0ms;
    --t-2: 0ms;
    --t-3: 0ms;
    --t-4: 0ms;
  }
}
`;

const targets = ["design/tokens.css", "packages/ui/src/tokens.css"];
let failed = false;
for (const rel of targets) {
	const file = join(root, rel);
	if (check) {
		if (!existsSync(file) || readFileSync(file, "utf8") !== css) {
			console.error(`stale tokens: ${rel}`);
			failed = true;
		}
	} else {
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, css);
		console.log(`wrote ${rel}`);
	}
}

if (check) {
	if (failed) {
		console.error("Run: node tools/build-tokens.mjs");
		process.exit(1);
	}
	console.log("tokens: ok");
}
