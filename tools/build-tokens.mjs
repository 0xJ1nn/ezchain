// Generate design/tokens.css and packages/ui/src/tokens.css from design/tokens.json.
// The JSON is canonical; never hand-edit the generated CSS.
// Usage: node tools/build-tokens.mjs [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";

const root = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const check = process.argv.includes("--check");
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));

const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

function flatten(value, path = [], out = []) {
	for (const [key, child] of Object.entries(value)) {
		if (key.startsWith("$")) continue;
		const next = [...path, kebab(key)];
		if (child && typeof child === "object" && !Array.isArray(child)) flatten(child, next, out);
		else out.push([next.join("-"), child]);
	}
	return out;
}

const entries = flatten({
	color: tokens.color,
	space: tokens.space,
	radius: tokens.radius,
	type: tokens.type,
	elevation: tokens.elevation,
	motion: tokens.motion,
});

const lines = entries.map(([name, value]) => `  --${name}: ${value};`);

const aliases = [
	["--bg", "--color-surface-canvas"],
	["--surface", "--color-surface-raised"],
	["--surface-2", "--color-surface-subtle"],
	["--surface-3", "--color-surface-sunken"],
	["--ink", "--color-text-primary"],
	["--ink-2", "--color-text-secondary"],
	["--muted", "--color-text-muted"],
	["--line", "--color-surface-hairline"],
	["--line-2", "--color-surface-border-strong"],
	["--dash", "--color-chart-axis"],
	["--ok", "--color-semantic-success-text"],
	["--ok-bg", "--color-semantic-success-bg"],
	["--err", "--color-semantic-danger-text"],
	["--err-bg", "--color-semantic-danger-bg"],
	["--warn", "--color-semantic-warning-text"],
	["--warn-bg", "--color-semantic-warning-bg"],
	["--info", "--color-semantic-info-text"],
	["--info-bg", "--color-semantic-info-bg"],
	["--accent", "--color-accent-primary"],
	["--r", "--radius-md"],
	["--r-sm", "--radius-sm"],
	["--sans", "--type-family-sans"],
	["--mono", "--type-family-mono"],
	["--shadow", "--elevation-0"],
];

const css = `/* generated by tools/build-tokens.mjs from design/tokens.json — do not edit */
:root {
${lines.join("\n")}
${aliases.map(([a, b]) => `  ${a}: var(${b});`).join("\n")}
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --motion-fast: 0ms;
    --motion-base: 0ms;
    --motion-slow: 0ms;
  }
}
`;

const targets = ["design/tokens.css", "packages/ui/src/tokens.css"];
let failed = false;
for (const rel of targets) {
	const file = join(root, rel);
	if (check) {
		if (!existsSync(file) || readFileSync(file, "utf8") !== css) {
			console.error(`stale tokens: ${rel}`);
			failed = true;
		}
	} else {
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, css);
		console.log(`wrote ${rel}`);
	}
}

if (check) {
	if (failed) {
		console.error("Run: node tools/build-tokens.mjs");
		process.exit(1);
	}
	console.log("tokens: ok");
}
